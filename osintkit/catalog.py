@dataclass(frozen=True)
class Tool:
    id: str
    name: str
    category: str
    kinds: tuple[str, ...]
    description: str
    module: str | None = None
    commands: dict[str, str] = field(default_factory=dict)
    url: str = ""
    keys: tuple[str, ...] = ()
    bins: tuple[str, ...] = ()
    install: dict[str, str] = field(default_factory=dict)
    passive: bool = True
    tags: tuple[str, ...] = ()
    options: dict[str, object] = field(default_factory=dict)
    timeout: int = 0
    home: str = ""

    def command_for(self, kind: str) -> str:
        return self.commands.get(kind, "")

    @property
    def kind_label(self) -> str:
        return ", ".join(self.kinds)

    @property
    def mode(self) -> str:
        if self.module:
            return "módulo"
        if self.commands:
            return "binario"
        if self.url:
            return "web"
        return "?"


def _tool(
    tid: str,
    name: str,
    category: str,
    kinds: tuple[str, ...],
    description: str,
    *,
    module: str | None = None,
    cmd: str = "",
    commands: dict[str, str] | None = None,
    url: str = "",
    keys: tuple[str, ...] = (),
    bins: tuple[str, ...] = (),
    install: dict[str, str] | None = None,
    passive: bool = True,
    tags: tuple[str, ...] = (),
    options: dict[str, object] | None = None,
    timeout: int = 0,
    home: str = "",
) -> Tool:
    cmds = dict(commands or {})
    if cmd:
        for kind in kinds:
            cmds.setdefault(kind, cmd)
    return Tool(
        id=tid,
        name=name,
        category=category,
        kinds=tuple(kinds),
        description=description,
        module=module,
        commands=cmds,
        url=url,
        keys=tuple(keys),
        bins=tuple(bins),
        install=dict(install or {}),
        passive=passive,
        tags=tuple(tags),
        options=dict(options or {}),
        timeout=timeout,
        home=home,
    )


def _slug(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", value.casefold()).strip("_")
    return slug or "fuente"


def _phone_source_tools() -> list[Tool]:
    """Convierte phone_sources.json en recursos web consultables."""
    out: list[Tool] = []
    used: set[str] = set()
    for source in _phone_source_data():
        name = str(source.get("name") or "").strip()
        url = str(source.get("url") or "").strip()
        if not name or not url:
            continue
        base = "phone_src_" + _slug(name)
        tool_id = base
        suffix = 2
        while tool_id in used:
            tool_id = f"{base}_{suffix}"
            suffix += 1
        used.add(tool_id)
        region = str(source.get("region") or "Global")
        description = str(source.get("description") or "")
        tags = source.get("tags") if isinstance(source.get("tags"), list) else []
        tag_tuple = tuple(str(tag) for tag in tags)
        out.append(
            _tool(
                tool_id,
                f"{name} ({region})",
                "phone",
                ("phone",),
                description or f"Consulta de teléfono en {name}.",
                url=url,
                tags=("web", "teléfono", *tag_tuple),
            )
        )
    return out


