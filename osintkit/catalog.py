BY_ID: dict[str, Tool] = {tool.id: tool for tool in TOOLS}
_TOOL_ORDER = {tool.id: i for i, tool in enumerate(TOOLS)}


def register_tool(tool: Tool) -> None:
    """Registra una herramienta de plugin si el id no existe."""
    if tool.id in BY_ID:
        return
    TOOLS.append(tool)
    BY_ID[tool.id] = tool
    _TOOL_ORDER[tool.id] = len(_TOOL_ORDER)


def get_tool(tool_id: str) -> Tool | None:
    return BY_ID.get(tool_id)


def resolve_profile(name: str | None, kind: str) -> str:
    if not name:
        return DEFAULT_PROFILES.get(kind, "keyword")
    key = name.strip().lower()
    key = PROFILE_ALIASES.get(key, key)
    if key in {"deep", "profundo"} and f"{kind}-deep" in PROFILES:
        return f"{kind}-deep"
    if key in PROFILES:
        return key
    if key in DEFAULT_PROFILES:
        return DEFAULT_PROFILES[key]
    return DEFAULT_PROFILES.get(kind, "keyword")


def profile_tools(name: str, kind: str | None = None) -> list[Tool]:
    profile = PROFILES.get(name, {})
    ids = list(profile.get("tools", []))  # type: ignore[arg-type]
    tools = [BY_ID[i] for i in ids if i in BY_ID]
    if kind:
        tools = [t for t in tools if kind in t.kinds]
    return tools


def profiles_for_kind(kind: str) -> list[str]:
    """Perfiles aplicables a un tipo de objetivo, en orden de catálogo."""
    return [
        name for name, profile in PROFILES.items()
        if kind in profile.get("kinds", ())  # type: ignore[operator]
    ]


def profile_has_active(name: str, kind: str | None = None) -> bool:
    return any(not tool.passive for tool in profile_tools(name, kind))


def tools_for_kind(kind: str) -> list[Tool]:
    return [t for t in TOOLS if kind in t.kinds]


